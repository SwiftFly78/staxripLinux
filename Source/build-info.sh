#!/bin/sh
# Writes the version and the changes of the Linux port from its git tags for the build,
# see "Versioning" in Docs/Introduction/Linux.md.
# usage: build-info.sh <output folder>
set -u

out=$(mkdir -p "$1" && cd "$1" && pwd) || exit 1
cd "$(dirname "$0")"

# builds without git, like from a source archive, have no version
version=$(git describe --tags --match 'v[0-9]*' --dirty 2> /dev/null | tr -cd 'A-Za-z0-9.+-') || version=

# one line per version with tag, date and change, newest first
changes=$(git tag --list 'v*' --contains v1.0.0 --merged HEAD --sort=-v:refname \
    --format='%(refname:short)%09%(if)%(*committerdate)%(then)%(*committerdate:short)%(else)%(committerdate:short)%(end)%09%(if)%(*subject)%(then)%(*subject)%(else)%(subject)%(end)' \
    2> /dev/null) || changes=

# unchanged files don't make the project compile again
write() {
    if [ ! -f "$1" ] || [ "$(cat "$1")" != "$2" ]; then
        printf '%s\n' "$2" > "$1"
    fi
}

write "$out/BuildInfo.vb" "'generated by build-info.sh
Public Module BuildInfo
    Public Const PortVersion As String = \"$version\"
End Module"

write "$out/CHANGELOG-LINUX.txt" "$changes"
